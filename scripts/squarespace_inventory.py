#!/usr/bin/env python3
"""Inventory local Squarespace WordPress XML exports without network access."""
import argparse
from html.parser import HTMLParser
import json
from pathlib import Path
import sys
from urllib.parse import urlsplit
import xml.etree.ElementTree as ET

WP = '{http://wordpress.org/export/1.2/}'
CONTENT = '{http://purl.org/rss/1.0/modules/content/}encoded'
ROOT = Path(__file__).resolve().parents[1]


class ReadableHTML(HTMLParser):
    """Extract text and URL references; leave source HTML untouched."""
    BLOCKS = {'p', 'div', 'section', 'article', 'br', 'li', 'h1', 'h2', 'h3',
              'h4', 'h5', 'h6', 'blockquote', 'tr', 'hr'}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts, self.links, self.images = [], [], []
        self.hidden = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag in {'script', 'style'}:
            self.hidden.append(tag)
        if self.hidden:
            return
        if tag in self.BLOCKS:
            self.parts.append('\n')
        if tag == 'a' and attrs.get('href'):
            self.links.append(attrs['href'])
        if tag in {'img', 'source'}:
            for key in ('src', 'data-src', 'data-image'):
                if attrs.get(key):
                    self.images.append(attrs[key])
            for key in ('srcset', 'data-srcset'):
                for candidate in attrs.get(key, '').split(','):
                    if candidate.strip():
                        self.images.append(candidate.strip().split()[0])

    def handle_endtag(self, tag):
        if self.hidden:
            if tag == self.hidden[-1]:
                self.hidden.pop()
            return
        if tag in self.BLOCKS:
            self.parts.append('\n')

    def handle_data(self, data):
        if not self.hidden:
            self.parts.append(data)

    def result(self):
        lines = [' '.join(line.split()) for line in ''.join(self.parts).splitlines()]
        return ('\n'.join(line for line in lines if line),
                list(dict.fromkeys(self.links)), list(dict.fromkeys(self.images)))


def inventory(source_dir):
    pages, problems, sources = [], [], []
    files = sorted(source_dir.glob('*.xml'))
    if not files:
        problems.append({'source': str(source_dir), 'message': 'No XML exports found.'})
    for path in files:
        sources.append(path.name)
        try:
            root = ET.parse(path).getroot()
        except (ET.ParseError, OSError) as exc:
            problems.append({'source': path.name, 'message': str(exc)})
            continue
        items = root.findall('./channel/item')
        if not items:
            problems.append({'source': path.name, 'message': 'No channel/item records found.'})
        for index, item in enumerate(items, 1):
            def field(name):
                return item.findtext(name) or None
            html = field(CONTENT)
            parser = ReadableHTML()
            parser.feed(html or '')
            parser.close()
            text, links, images = parser.result()
            link = field('link')
            try:
                original_path = urlsplit(link).path if link else None
            except ValueError:
                original_path = None
                problems.append({'source': path.name, 'item': index, 'message': 'Invalid original URL.'})
            page = {
                'source_file': path.name, 'source_item': index,
                'title': field('title'), 'original_url': link, 'original_path': original_path,
                'publication_date': field('pubDate'), 'post_date': field(WP + 'post_date'),
                'post_id': field(WP + 'post_id'), 'slug': field(WP + 'post_name'),
                'post_type': field(WP + 'post_type'), 'status': field(WP + 'status'),
                'readable_text': text, 'outgoing_links': links, 'image_urls': images,
                'source_html': html,
                'source_item_xml': ET.tostring(item, encoding='unicode'),
            }
            for key in ('title', 'original_url', 'publication_date', 'source_html'):
                if page[key] is None:
                    problems.append({'source': path.name, 'item': index, 'message': f'Missing {key}.'})
            pages.append(page)
    return {'schema_version': 1, 'source_files': sources, 'item_count': len(pages),
            'pages': pages, 'problems': problems}


def md_cell(value):
    return str(value if value is not None else '(missing)').replace('|', '\\|').replace('\n', ' ').replace('\r', ' ')


def summary(data):
    lines = ['# Squarespace content inventory', '',
             'Generated by `python3 scripts/squarespace_inventory.py`. Do not edit manually.', '',
             f"Exports: {len(data['source_files'])} · Items: {data['item_count']} · Problems: {len(data['problems'])}", '',
             '| Title | Original path | Publication date | Links | Images |',
             '| --- | --- | --- | ---: | ---: |']
    for page in data['pages']:
        lines.append('| ' + ' | '.join(md_cell(v) for v in (
            page['title'], page['original_path'], page['publication_date'],
            len(page['outgoing_links']), len(page['image_urls']))) + ' |')
    lines += ['', '## Parsing and missing-field reports', '']
    lines += [f"- {md_cell(p['source'])}, item {p.get('item', '—')}: {md_cell(p['message'])}" for p in data['problems']] or ['None.']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, default=ROOT / 'source/squarespace')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'tmp/inventory')
    parser.add_argument('--summary', type=Path, default=ROOT / 'docs/SQUARESPACE_INVENTORY.md')
    parser.add_argument('--expect-count', type=int)
    args = parser.parse_args()
    # Prevent accidental writes over any original export, including custom paths.
    for target in (args.output_dir / 'squarespace.json', args.summary):
        if target.resolve().is_relative_to(args.source_dir.resolve()):
            parser.error('Output destinations must be outside the source directory.')
    data = inventory(args.source_dir)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    args.summary.parent.mkdir(parents=True, exist_ok=True)
    (args.output_dir / 'squarespace.json').write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    args.summary.write_text(summary(data), encoding='utf-8')
    print(f"Inventoried {data['item_count']} items; {len(data['problems'])} problems.")
    for problem in data['problems']:
        print(json.dumps(problem, ensure_ascii=False), file=sys.stderr)
    mismatch = args.expect_count is not None and data['item_count'] != args.expect_count
    if mismatch:
        print(f'Expected {args.expect_count} items.', file=sys.stderr)
    return 1 if data['problems'] or mismatch else 0


if __name__ == '__main__':
    sys.exit(main())
